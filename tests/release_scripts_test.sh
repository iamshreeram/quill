#!/usr/bin/env bash
# shellcheck disable=SC2015  # "A && B || fail" is intentional in assertions
# Acceptance tests for scripts/check-version.sh, scripts/package.sh
# (spec: .ram-status/quill-modes-20251025-2255/DESIGN.md Rev 4, Part C).
# Hermetic: every test works on a throwaway fixture repo selected via QUILL_REPO_ROOT; nothing here
# touches the real repository, the network, or any remote.
set -u

HERE="$(cd "$(dirname "$0")" && pwd)"
SCRIPTS="$HERE/../scripts"
ROOT="$(mktemp -d "${TMPDIR:-/tmp}/quill-release-test.XXXXXX")"
PASS=0; FAILED=0; FAILED_NAMES=""
trap 'rm -rf "$ROOT"' EXIT

for s in check-version.sh package.sh; do
  [ -f "$SCRIPTS/$s" ] || { echo "FAIL: scripts/$s does not exist"; exit 1; }
done

OUT=""; ERR=""; CODE=0; CUR=""; T=""

new_test() { CUR="$1"; T="$ROOT/$1"; rm -rf "$T"; mkdir -p "$T"; OUT="$T/out.txt"; ERR="$T/err.txt"; : > "$OUT"; : > "$ERR"; }
fail() { echo "  FAIL [$CUR]: $*"; sed 's/^/  | /' "$OUT" | head -20; sed 's/^/  | /' "$ERR" | head -20; FAILED=$((FAILED + 1)); FAILED_NAMES="$FAILED_NAMES $CUR"; return 1; }
done_test() { if echo "$FAILED_NAMES" | grep -qw -- "$CUR"; then echo "FAIL $CUR"; else PASS=$((PASS + 1)); echo "ok   $CUR"; fi; }
run() { "$@" >"$OUT" 2>"$ERR"; CODE=$?; }
check_code() { [ "$CODE" -eq "$1" ] || fail "expected exit $1 got $CODE"; }
check_nonzero() { [ "$CODE" -ne 0 ] || fail "expected non-zero exit"; }
has() { cat "$OUT" "$ERR" | grep -qi -- "$1" || fail "output lacks '$1'"; }

# ---- fixture repo ----
make_repo() { # <dir> <version> [branch]
  local d="$1" v="$2" b="${3:-main}"
  mkdir -p "$d/src"
  cat > "$d/Cargo.toml" <<EOF
[package]
name = "quill"
version = "$v"
edition = "2021"
EOF
  cat > "$d/Cargo.lock" <<EOF
# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "other"
version = "$v"

[[package]]
name = "quill"
version = "$v"
dependencies = [
 "other",
]
EOF
  cat > "$d/CHANGELOG.md" <<EOF
# Changelog

## [Unreleased]

### Added
- Offline grammar mode.

## [$v] - 2025-01-01

### Added
- Initial release.
EOF
  echo "MIT" > "$d/LICENSE"; echo "readme" > "$d/README.md"; echo "# sample" > "$d/config.sample.toml"
  ( cd "$d" && git init -q -b "$b" . && git config user.email t@example.com && git config user.name t && git config commit.gpgsign false \
    && git config tag.gpgsign false && git add -A && git commit -q -m init )
}

# ───────── check-version.sh ─────────
r01_check_version() {
  new_test r01
  make_repo "$T/repo" 1.2.3
  # add a changelog heading for 1.2.3
  sed -i.bak 's/^## \[1.2.3\] - 2025-01-01/## [1.2.3] - 2025-01-01/' "$T/repo/CHANGELOG.md"
  QUILL_REPO_ROOT="$T/repo" run bash "$SCRIPTS/check-version.sh" v1.2.3;  check_code 0
  QUILL_REPO_ROOT="$T/repo" run bash "$SCRIPTS/check-version.sh" v1.2.4;  check_nonzero; has 'does not match'
  QUILL_REPO_ROOT="$T/repo" run bash "$SCRIPTS/check-version.sh" 1.2.3;   check_nonzero      # missing v prefix
  QUILL_REPO_ROOT="$T/repo" run bash "$SCRIPTS/check-version.sh" v1.2;    check_nonzero      # not SemVer
  QUILL_REPO_ROOT="$T/repo" run bash "$SCRIPTS/check-version.sh";         check_nonzero      # no argument
  # changelog heading missing for the version
  sed -i.bak 's/^## \[1.2.3\]/## [9.9.9]/' "$T/repo/CHANGELOG.md"
  QUILL_REPO_ROOT="$T/repo" run bash "$SCRIPTS/check-version.sh" v1.2.3;  check_nonzero; has 'changelog'
  # prerelease tag + matching Cargo version
  make_repo "$T/pre" 1.3.0-rc.1
  QUILL_REPO_ROOT="$T/pre" run bash "$SCRIPTS/check-version.sh" v1.3.0-rc.1; check_code 0
  done_test
}

# ───────── package.sh ─────────
r02_package_archives_and_checksums() {
  new_test r02
  make_repo "$T/repo" 1.2.3
  printf '#!/bin/sh\necho quill 1.2.3\n' > "$T/quill"; chmod 755 "$T/quill"
  mkdir -p "$T/dist"
  QUILL_REPO_ROOT="$T/repo" run bash "$SCRIPTS/package.sh" x86_64-unknown-linux-gnu 1.2.3 "$T/quill" "$T/dist"; check_code 0
  local a="$T/dist/quill-1.2.3-x86_64-unknown-linux-gnu.tar.gz"
  [ -f "$a" ] || fail "archive missing"
  local listing; listing="$(tar -tzf "$a" 2>/dev/null)"
  for m in quill LICENSE README.md config.sample.toml; do
    echo "$listing" | grep -qx "quill-1.2.3-x86_64-unknown-linux-gnu/$m" || fail "archive lacks $m"
  done
  [ -f "$T/dist/SHA256SUMS" ] || fail "SHA256SUMS missing"
  ( cd "$T/dist" && if command -v shasum >/dev/null; then shasum -a 256 -c SHA256SUMS >/dev/null 2>&1; else sha256sum -c SHA256SUMS >/dev/null 2>&1; fi ) || fail "checksum verification failed"
  # second target appends; re-running a target does not duplicate; file stays sorted
  QUILL_REPO_ROOT="$T/repo" run bash "$SCRIPTS/package.sh" aarch64-apple-darwin 1.2.3 "$T/quill" "$T/dist"; check_code 0
  QUILL_REPO_ROOT="$T/repo" run bash "$SCRIPTS/package.sh" aarch64-apple-darwin 1.2.3 "$T/quill" "$T/dist"; check_code 0
  [ "$(wc -l < "$T/dist/SHA256SUMS" | tr -d ' ')" = "2" ] || fail "expected 2 checksum lines, got: $(cat "$T/dist/SHA256SUMS")"
  [ "$(awk '{print $2}' "$T/dist/SHA256SUMS")" = "$(awk '{print $2}' "$T/dist/SHA256SUMS" | sort)" ] || fail "SHA256SUMS not sorted"
  ( cd "$T/dist" && if command -v shasum >/dev/null; then shasum -a 256 -c SHA256SUMS >/dev/null 2>&1; else sha256sum -c SHA256SUMS >/dev/null 2>&1; fi ) || fail "checksum verification failed after append"
  # windows -> zip containing quill.exe
  cp "$T/quill" "$T/quill.exe"
  QUILL_REPO_ROOT="$T/repo" run bash "$SCRIPTS/package.sh" x86_64-pc-windows-msvc 1.2.3 "$T/quill.exe" "$T/dist"; check_code 0
  local z="$T/dist/quill-1.2.3-x86_64-pc-windows-msvc.zip"
  [ -f "$z" ] || fail "zip missing"
  python3 - "$z" <<'PY' || fail "zip lacks quill.exe"
import sys, zipfile
names = zipfile.ZipFile(sys.argv[1]).namelist()
assert "quill-1.2.3-x86_64-pc-windows-msvc/quill.exe" in names, names
PY
  grep -q 'quill-1.2.3-x86_64-pc-windows-msvc.zip' "$T/dist/SHA256SUMS" || fail "zip not in SHA256SUMS"
  # errors
  QUILL_REPO_ROOT="$T/repo" run bash "$SCRIPTS/package.sh" x86_64-unknown-linux-gnu 1.2.3 "$T/nope" "$T/dist"; check_nonzero
  QUILL_REPO_ROOT="$T/repo" run bash "$SCRIPTS/package.sh" x86_64-unknown-linux-gnu 1.2.3; check_nonzero
  done_test
}

r07_scripts_are_syntactically_valid_and_executable_bash() {
  new_test r07
  for s in check-version.sh package.sh changelog-section.sh; do
    bash -n "$SCRIPTS/$s" || fail "$s syntax"
    head -1 "$SCRIPTS/$s" | grep -q '^#!' || fail "$s shebang"
    [ -x "$SCRIPTS/$s" ] || fail "$s not executable"
    grep -q 'set -[a-z]*e' "$SCRIPTS/$s" || fail "$s does not set -e"
  done
  if command -v shellcheck >/dev/null 2>&1; then
    shellcheck "$SCRIPTS"/*.sh >"$OUT" 2>&1 || fail "shellcheck findings"
  fi
  done_test
}

r08_changelog_section_extraction() {
  new_test r08
  [ -f "$SCRIPTS/changelog-section.sh" ] || { fail "scripts/changelog-section.sh does not exist"; done_test; return; }
  make_repo "$T/repo" 1.2.3
  QUILL_REPO_ROOT="$T/repo" run bash "$SCRIPTS/changelog-section.sh" 1.2.3; check_code 0
  grep -q 'Initial release' "$OUT" || fail "section body missing"
  grep -q 'Offline grammar mode' "$OUT" && fail "leaked the Unreleased section"
  grep -q '^## ' "$OUT" && fail "heading must not be included"
  QUILL_REPO_ROOT="$T/repo" run bash "$SCRIPTS/changelog-section.sh" 9.9.9; check_nonzero
  QUILL_REPO_ROOT="$T/repo" run bash "$SCRIPTS/changelog-section.sh"; check_nonzero
  done_test
}

r01_check_version
r02_package_archives_and_checksums
r07_scripts_are_syntactically_valid_and_executable_bash
r08_changelog_section_extraction

echo
echo "passed: $PASS   failed: $FAILED"
[ "$FAILED" -eq 0 ] || { echo "failed tests:$FAILED_NAMES"; exit 1; }
exit 0
