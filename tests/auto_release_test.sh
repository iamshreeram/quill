B() { local d="$1"; shift; QUILL_REPO_ROOT="$d" run bash "$SCRIPTS/bump-version.sh" "$@"; }
b01_generated_notes_and_files() {
  new_test b01; mk_auto "$T/repo" 0.5.0
  c "$T/repo" "feat: add widget"
  c "$T/repo" "fix: handle \$(touch $T/PWNED_X) and \`touch $T/PWNED_Y\` safely"
  c "$T/repo" "chore(release): v9.9.9 [skip ci]"
  B "$T/repo" 0.6.0 --prev-tag v0.5.0 --date 2026-01-02; check_code 0
  [ "$(toml_ver "$T/repo")" = 0.6.0 ] || fail "Cargo.toml not bumped"
  [ "$(lock_ver "$T/repo")" = 0.6.0 ] || fail "Cargo.lock quill not bumped"
  awk '/^name = "other"/{f=1;next} f&&/^version/{print;exit}' "$T/repo/Cargo.lock" | grep -q '"0.5.0"' || fail "other package changed"
  grep -q '^## \[0.6.0\] - 2026-01-02$' "$T/repo/CHANGELOG.md" || fail "heading missing"
  grep -q 'feat: add widget' "$T/repo/CHANGELOG.md" || fail "commit subject missing from notes"
  grep -q 'v9.9.9' "$T/repo/CHANGELOG.md" && fail "release commit leaked into notes"
  [ ! -e "$T/PWNED_X" ] && [ ! -e "$T/PWNED_Y" ] || fail "commit subject was executed"
  unrel=$(grep -n '^## \[Unreleased\]' "$T/repo/CHANGELOG.md" | head -1 | cut -d: -f1); new=$(grep -n '^## \[0.6.0\]' "$T/repo/CHANGELOG.md" | head -1 | cut -d: -f1); old=$(grep -n '^## \[0.5.0\]' "$T/repo/CHANGELOG.md" | head -1 | cut -d: -f1)
  [ -n "$unrel" ] && [ "$unrel" -lt "$new" ] && [ "$new" -lt "$old" ] || fail "section order wrong ($unrel/$new/$old)"
  QUILL_REPO_ROOT="$T/repo" run bash "$SCRIPTS/changelog-section.sh" 0.6.0; check_code 0
  [ -s "$OUT" ] || fail "empty release notes"
  QUILL_REPO_ROOT="$T/repo" run bash "$SCRIPTS/check-version.sh" v0.6.0; check_code 0
  done_test
}
