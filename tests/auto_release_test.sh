# Acceptance tests for the automatic release machinery:
#   scripts/next-version.sh, bump-version.sh, plan-release.sh, finish-release.sh, mark-published.sh
#   plus static policy checks on the workflows (spec: .ram-status/quill-auto-release-20261026-0036/DESIGN.md Rev 4).
# Hermetic: throwaway fixture repos with a local bare "origin", a fake `gh` on PATH, no network.
set -u

HERE="$(cd "$(dirname "$0")" && pwd)"
REPO="$(cd "$HERE/.." && pwd)"
SCRIPTS="$REPO/scripts"
ROOT="$(mktemp -d "${TMPDIR:-/tmp}/quill-autorelease-test.XXXXXX")"
PASS=0; FAILED=0; FAILED_NAMES=""
trap 'rm -rf "$ROOT"' EXIT

BOT_EMAIL='41898282+github-actions[bot]@users.noreply.github.com'

# ONLY="n b" runs just the tests whose names start with one of the words (used while scripts are built one by one);
# a full run (ONLY unset) requires every script to exist.
if [ -z "${ONLY:-}" ]; then
  for s in next-version.sh bump-version.sh plan-release.sh finish-release.sh mark-published.sh; do
    [ -f "$SCRIPTS/$s" ] || { echo "FAIL: scripts/$s does not exist"; exit 1; }
  done
fi
selected() { [ -z "${ONLY:-}" ] && return 0; local w; for w in $ONLY; do case "$1" in "$w"*) return 0 ;; esac; done; return 1; }

OUT=""; ERR=""; CODE=0; CUR=""; T=""

new_test() { CUR="$1"; T="$ROOT/$1"; rm -rf "$T"; mkdir -p "$T"; OUT="$T/out.txt"; ERR="$T/err.txt"; : > "$OUT"; : > "$ERR"; }
fail() { echo "  FAIL [$CUR]: $*"; sed 's/^/  | /' "$OUT" | head -20; sed 's/^/  | /' "$ERR" | head -20; FAILED=$((FAILED + 1)); FAILED_NAMES="$FAILED_NAMES $CUR"; return 1; }
done_test() { if echo "$FAILED_NAMES" | grep -qw -- "$CUR"; then echo "FAIL $CUR"; else PASS=$((PASS + 1)); echo "ok   $CUR"; fi; }
run() { "$@" >"$OUT" 2>"$ERR"; CODE=$?; }
check_code() { [ "$CODE" -eq "$1" ] || fail "expected exit $1 got $CODE"; }
check_nonzero() { [ "$CODE" -ne 0 ] || fail "expected non-zero exit"; }
has() { cat "$OUT" "$ERR" | grep -qi -- "$1" || fail "output lacks '$1'"; }
kv() { grep "^$1=" "$OUT" | head -1 | cut -d= -f2-; }
want() { [ "$(kv "$1")" = "$2" ] || fail "expected $1=$2 got '$(kv "$1")'"; }

# ---- fixtures ----
# mk_auto <dir> <version> [unreleased-body]: repo with annotated tag v<version>, bare origin at <dir>/../remote.git
mk_auto() {
  local d="$1" v="$2" body="${3:-}"
  mkdir -p "$d/src"
  cat > "$d/Cargo.toml" <<EOF
[package]
name = "quill"
version = "$v"
edition = "2021"
EOF
  cat > "$d/Cargo.lock" <<EOF
# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "other"
version = "$v"

[[package]]
name = "quill"
version = "$v"
dependencies = [
 "other",
]
EOF
  {
    printf '# Changelog\n\n## [Unreleased]\n'
    [ -n "$body" ] && printf '\n%s\n' "$body"
    printf '\n## [%s] - 2025-01-01\n\n### Added\n- Initial release.\n' "$v"
  } > "$d/CHANGELOG.md"
  echo MIT > "$d/LICENSE"; echo readme > "$d/README.md"; echo '// x' > "$d/src/main.rs"
  ( cd "$d" && git init -q -b main . && git config user.email t@example.com && git config user.name t \
    && git config commit.gpgsign false && git config tag.gpgsign false && git add -A && git commit -q -m init \
    && git tag -a "v$v" -m "v$v" )
  git init -q -b main --bare "$d/../remote.git"
  ( cd "$d" && git remote add origin "$d/../remote.git" && git push -q origin main --tags )
}
# c <dir> <subject> [file]: add a commit that touches <file> (default src/file.rs)
c() {
  local d="$1" s="$2" f="${3:-src/file.rs}"
  mkdir -p "$d/$(dirname "$f")"; echo "$s $RANDOM$RANDOM" >> "$d/$f"
  git -C "$d" add -A; git -C "$d" commit -q -m "$s"
}
head_sha() { git -C "$1" rev-parse HEAD; }
# rel <dir> <version>: automation-style release commit + annotated tag, pushed to origin
rel() {
  local d="$1" v="$2"
  sed -i.bak "s/^version = \".*\"/version = \"$v\"/" "$d/Cargo.toml"; rm -f "$d/Cargo.toml.bak"
  git -C "$d" add -A
  git -C "$d" -c user.email="$BOT_EMAIL" -c user.name='github-actions[bot]' commit -q --allow-empty -m "chore(release): v$v [skip ci]"
  git -C "$d" tag -a "v$v" -m "v$v"
  git -C "$d" push -q origin main "v$v"
}
mark() { git -C "$1" push -q origin "$2^{commit}:refs/published/$2"; }

# fake gh: state in $FAKE_GH_STATE (<tag>.published | <tag>.draft), calls logged to $FAKE_GH_STATE/log
mk_gh() {
  mkdir -p "$T/bin" "$T/ghstate"
  cat > "$T/bin/gh" <<'EOF'
#!/usr/bin/env bash
S="${FAKE_GH_STATE:?}"
[ "$1" = release ] || { echo "fake gh: unsupported $*" >&2; exit 9; }
sub="$2"; tag="$3"; shift 3
case "$sub" in
  view)
    if [ -e "$S/$tag.published" ]; then echo false; exit 0; fi
    if [ -e "$S/$tag.draft" ]; then echo true; exit 0; fi
    exit 1 ;;
  create)
    [ "${FAKE_GH_FAIL:-}" = create ] && exit 1
    files=""; flags=""
    for a in "$@"; do if [ -f "$a" ]; then files="$files,$(basename "$a")"; else flags="$flags $a"; fi; done
    echo "create $tag files=$files flags=$flags" >> "$S/log"; : > "$S/$tag.draft" ;;
  upload)
    [ "${FAKE_GH_FAIL:-}" = upload ] && exit 1
    files=""; flags=""
    for a in "$@"; do if [ -f "$a" ]; then files="$files,$(basename "$a")"; else flags="$flags $a"; fi; done
    echo "upload $tag files=$files flags=$flags" >> "$S/log" ;;
  edit)
    case " $* " in
      *" --draft=false "*)
        [ "${FAKE_GH_FAIL:-}" = publish ] && exit 1
        echo "publish $tag" >> "$S/log"; rm -f "$S/$tag.draft"; : > "$S/$tag.published" ;;
      *) echo "edit $tag $*" >> "$S/log" ;;
    esac ;;
  *) exit 9 ;;
esac
EOF
  chmod +x "$T/bin/gh"
}
gh_state() { echo "$T/ghstate"; }
glog() { cat "$T/ghstate/log" 2>/dev/null; }

lock_ver() { awk '/^name = "quill"/{f=1;next} f&&/^version/{gsub(/[^0-9.]/,"",$3); print $3; exit}' "$1/Cargo.lock"; }
toml_ver() { sed -n 's/^version = "\(.*\)"/\1/p' "$1/Cargo.toml" | head -1; }

