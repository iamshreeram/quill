# ───────── static policy checks ─────────
s01_workflow_policy() {
  new_test s01
  # YAML -> JSON with whatever parser exists (PyYAML, else Ruby's Psych: present on stock macOS and Ubuntu runners)
  if python3 -c 'import yaml' 2>/dev/null; then
    python3 -c 'import sys, json, yaml; print(json.dumps({str(k): v for k, v in yaml.safe_load(open(sys.argv[1])).items()}))' "$REPO/.github/workflows/release.yml" > "$T/release.json" 2> "$ERR"
  elif command -v ruby >/dev/null 2>&1; then
    ruby -ryaml -rjson -e 'puts JSON.generate(YAML.load_file(ARGV[0]))' "$REPO/.github/workflows/release.yml" > "$T/release.json" 2> "$ERR"
  else
    echo "no YAML parser (PyYAML or ruby) available" > "$ERR"; : > "$T/release.json"
  fi
  python3 - "$T/release.json" > "$OUT" 2>> "$ERR" <<'PY'
import sys, re, json
w = json.load(open(sys.argv[1]))
on = w.get("true", w.get("True", w.get("on")))
if on is None:
    print("cannot find the 'on' trigger block"); sys.exit(1)
problems = []
if "tags" in (on.get("push") or {}): problems.append("release.yml must not trigger on tags")
if (on.get("push") or {}).get("branches") != ["main"]: problems.append("push trigger must be exactly branches: [main]")
if "paths-ignore" in (on.get("push") or {}) or "paths" in (on.get("push") or {}): problems.append("no path filters on the push trigger (plan decides)")
if "workflow_dispatch" not in on: problems.append("workflow_dispatch missing")
conc = w.get("concurrency") or {}
if conc.get("cancel-in-progress") is not False or not conc.get("group"): problems.append("concurrency must queue (cancel-in-progress: false)")
if (w.get("permissions") or {}).get("contents") != "read": problems.append("top-level permissions must be contents: read")
jobs = w["jobs"]
for need in ("plan", "verify", "build", "publish"):
    if need not in jobs: problems.append("job missing: " + need)
perm = (jobs.get("publish") or {}).get("permissions") or {}
if perm.get("contents") != "write": problems.append("publish needs contents: write")
for name in ("plan", "verify", "build"):
    if (jobs.get(name, {}).get("permissions") or {}).get("contents") == "write": problems.append(name + " must not have write permission")
for name, job in jobs.items():
    for step in job.get("steps", []):
        run = step.get("run")
        if run and re.search(r"\$\{\{(?!\s*matrix\.)", run):
            problems.append("expression interpolated in run body of %s: %s" % (name, step.get("name")))
        if "actions/checkout" in str(step.get("uses", "")) and name in ("plan", "verify", "build", "publish"):
            if str((step.get("with") or {}).get("fetch-depth")) != "0": problems.append("checkout without fetch-depth: 0 in " + name)
if problems:
    print("\n".join(problems)); sys.exit(1)
PY
  CODE=$?
  check_code 0
  done_test
}
